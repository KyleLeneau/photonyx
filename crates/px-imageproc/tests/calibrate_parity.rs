//! Calibration parity against Siril, on the real-frame corpus
//! (ADR 007, P4-T5).
//!
//! References come from `cargo xtask siril-reference --calibration`. Neither
//! the corpus nor the references are committed, so these tests skip when
//! absent.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use px_fits::reader::FitsReader;
use px_imageproc::Frame;
use px_imageproc::calibrate::{self, CalibrationOptions, Masters};
use px_imageproc::stats::ChannelStats;

const ADU: f64 = 65535.0;

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("repo root")
        .to_path_buf()
}

/// Reference sets, one per corpus. Both are generated by
/// `cargo xtask siril-reference --calibration`, the OSC one with
/// `--corpus data/corpus-osc --out data/reference-osc`.
fn reference_roots() -> Vec<(&'static str, PathBuf)> {
    [("mono", "data/reference"), ("osc", "data/reference-osc")]
        .into_iter()
        .map(|(name, dir)| (name, repo_root().join(dir)))
        .filter(|(_, dir)| dir.is_dir())
        .collect()
}

fn reference(root: &Path, relative: &str) -> Option<PathBuf> {
    let p = root.join(relative);
    p.exists().then_some(p)
}

fn load(path: &Path) -> Frame {
    let reader = FitsReader::open(path).expect("open");
    let hdu = reader.primary_image().expect("image");
    Frame::from_hdu(&hdu).expect("decode")
}

struct Diff {
    max_abs: f64,
    rms: f64,
    mean_signed: f64,
}

fn compare(ours: &[f32], theirs: &[f32]) -> Diff {
    assert_eq!(ours.len(), theirs.len());
    let mut max_abs = 0.0f64;
    let mut sum_sq = 0.0f64;
    let mut sum = 0.0f64;
    for (a, b) in ours.iter().zip(theirs) {
        let d = (*a as f64 - *b as f64) * ADU;
        max_abs = max_abs.max(d.abs());
        sum_sq += d * d;
        sum += d;
    }
    Diff {
        max_abs,
        rms: (sum_sq / ours.len() as f64).sqrt(),
        mean_signed: sum / ours.len() as f64,
    }
}

/// The light frame Siril calibrated, read back from the manifest so both
/// sides operate on the same input.
fn source_light(root: &Path) -> Option<PathBuf> {
    let text = std::fs::read_to_string(reference(root, "calibrated/source.txt")?).ok()?;
    let line = text.lines().find(|l| l.starts_with("light: "))?;
    let path = PathBuf::from(line.trim_start_matches("light: ").trim());
    path.exists().then_some(path)
}

/// The `pp_` frame Siril produced.
fn calibrated_reference(root: &Path) -> Option<PathBuf> {
    std::fs::read_dir(root.join("calibrated"))
        .ok()
        .and_then(|d| {
            d.filter_map(|e| e.ok().map(|e| e.path())).find(|p| {
                p.file_name()
                    .and_then(|n| n.to_str())
                    .is_some_and(|n| n.starts_with("pp_"))
            })
        })
}

/// How the clamping rule in `calibrate::ops` actually bit on a real frame.
struct ClampCensus {
    negative: usize,
    saturated: usize,
    most_negative: f32,
    total: usize,
}

fn census(data: &[f32]) -> ClampCensus {
    let mut negative = 0;
    let mut saturated = 0;
    let mut most_negative = 0.0f32;
    for &v in data {
        if v < 0.0 {
            negative += 1;
            most_negative = most_negative.min(v);
        } else if v >= 1.0 {
            saturated += 1;
        }
    }
    ClampCensus {
        negative,
        saturated,
        most_negative,
        total: data.len(),
    }
}

/// Reads several 61 MP frames per corpus; seconds optimized, minutes in a
/// debug build.
#[test]
#[cfg_attr(debug_assertions, ignore = "reads 61 MP frames; run with --release")]
fn a_calibrated_light_matches_siril() {
    let roots = reference_roots();
    if roots.is_empty() {
        eprintln!(
            "skipping: run `cargo xtask siril-reference --calibration` with a corpus under \
             data/corpus-mono (and --corpus data/corpus-osc --out data/reference-osc)"
        );
        return;
    }

    let mut report_text = String::new();
    let mut compared = 0;

    for (corpus_name, root) in roots {
        let (Some(light_path), Some(dark), Some(flat), Some(expected)) = (
            source_light(&root),
            reference(&root, "masters/master_dark.fits"),
            reference(&root, "masters/master_flat_winsorized.fits"),
            calibrated_reference(&root),
        ) else {
            eprintln!(
                "skipping {corpus_name}: incomplete reference under {}",
                root.display()
            );
            continue;
        };
        compared += 1;

        let mut frame = load(&light_path);
        let dark = load(&dark);
        let flat = load(&flat);

        // No master bias here, deliberately. The master dark is a median of
        // raw darks, so it already carries the bias pedestal; the flat was
        // itself bias-calibrated before stacking. Subtracting a master bias as
        // well would remove that pedestal twice, which is what the earlier
        // version of this test did and why its output was 99.8% negative.
        let masters = Masters {
            dark: Some(&dark),
            flat: Some(&flat),
            ..Default::default()
        };
        let report = calibrate::calibrate(&mut frame, &masters, &CalibrationOptions::default())
            .expect("calibrate");

        let theirs = load(&expected);
        assert_eq!(
            frame.dims(),
            theirs.dims(),
            "{corpus_name}: dimensions differ"
        );

        let diff = compare(frame.data(), theirs.data());
        let ours_stats = ChannelStats::compute(frame.channel(0), frame.width(), frame.height());
        let theirs_stats =
            ChannelStats::compute(theirs.channel(0), theirs.width(), theirs.height());
        let sigma_bg = theirs_stats.background_noise * ADU;

        let ours_census = census(frame.data());
        let theirs_census = census(theirs.data());

        let _ = writeln!(
            report_text,
            "[{corpus_name}] {}\n               max |delta| {:.4} ADU ({:.4} sigma_bg), rms {:.5} ADU, mean signed {:+.6} ADU\n               median  ours {:.4}  siril {:.4}\n               bgnoise ours {:.4}  siril {:.4}  (sigma_bg = {:.4} ADU)\n               flat level {:.2} ADU\n               negative pixels: ours {:.3}% (min {:.1} ADU = {:.3} unit), siril {:.3}% (min {:.1} ADU)\n               saturated pixels: ours {:.4}%, siril {:.4}%\n               destroyed by clamps: {} floored to zero, {} saturated, of {} pixels",
            light_path.file_name().unwrap().to_string_lossy(),
            diff.max_abs,
            diff.max_abs / sigma_bg,
            diff.rms,
            diff.mean_signed,
            ours_stats.median as f64 * ADU,
            theirs_stats.median as f64 * ADU,
            ours_stats.background_noise * ADU,
            theirs_stats.background_noise * ADU,
            sigma_bg,
            report.flat_level.unwrap_or(0.0) as f64 * ADU,
            100.0 * ours_census.negative as f64 / ours_census.total as f64,
            ours_census.most_negative as f64 * ADU,
            ours_census.most_negative,
            100.0 * theirs_census.negative as f64 / theirs_census.total as f64,
            theirs_census.most_negative as f64 * ADU,
            100.0 * ours_census.saturated as f64 / ours_census.total as f64,
            100.0 * theirs_census.saturated as f64 / theirs_census.total as f64,
            report.floored_pixels,
            report.saturated_pixels,
            ours_census.total,
        );

        let out_dir = repo_root().join("data/output/calibrated");
        std::fs::create_dir_all(&out_dir).expect("create output dir");
        let out = out_dir.join(format!(
            "{corpus_name}_native_{}",
            expected.file_name().unwrap().to_string_lossy()
        ));
        frame.write(&out, &[]).expect("write calibrated frame");

        // With the masters composed the way the project builds them — a raw
        // median dark that carries the bias, and a bias-calibrated flat — a
        // calibrated light's sky sits just above zero. Only the low tail of
        // its noise crosses into negative.
        assert!(
            report.negative_ratio < 0.25,
            "{corpus_name}: {:.2}% of pixels came out negative — masters do not match the lights",
            report.negative_ratio * 100.0
        );
        assert!(
            ours_stats.median > 0.0,
            "{corpus_name}: calibrated median is {:.2} ADU; correctly calibrated sky is positive",
            ours_stats.median as f64 * ADU
        );

        // The -1.0 floor is destructive: anything past it becomes exactly zero
        // and its value is gone. On a correctly calibrated frame it should
        // barely fire — the deepest negatives come from hot pixels in the
        // dark, which land around -0.8 to -0.95 and stay just inside it. The
        // bound is a small fraction of the frame rather than zero, because a
        // sensor with enough saturated dark pixels legitimately produces some.
        let floored_fraction = report.floored_pixels as f64 / ours_census.total as f64;
        assert!(
            floored_fraction < 0.001,
            "{corpus_name}: {} pixels ({:.4}%) were driven past -1.0 and zeroed — \
             the masters do not match the lights",
            report.floored_pixels,
            floored_fraction * 100.0
        );
        // And the two engines must agree on how much of the frame is negative.
        let ours_pct = ours_census.negative as f64 / ours_census.total as f64;
        let theirs_pct = theirs_census.negative as f64 / theirs_census.total as f64;
        assert!(
            (ours_pct - theirs_pct).abs() < 0.001,
            "{corpus_name}: negative fraction differs — ours {:.4}%, siril {:.4}%",
            ours_pct * 100.0,
            theirs_pct * 100.0
        );

        // ADR 007's bound for a mono light: 0.05 sigma_bg max, 0.01 sigma_bg RMS.
        assert!(
            diff.max_abs < 0.05 * sigma_bg,
            "{corpus_name}: worst pixel differs by {:.4} ADU = {:.3} sigma_bg (bound 0.05)",
            diff.max_abs,
            diff.max_abs / sigma_bg
        );
        assert!(
            diff.rms < 0.01 * sigma_bg,
            "{corpus_name}: rms difference {:.5} ADU = {:.4} sigma_bg (bound 0.01)",
            diff.rms,
            diff.rms / sigma_bg
        );
    }

    println!("{report_text}");
    let _ = std::fs::write(
        repo_root().join("data/output/calibrate-parity.txt"),
        &report_text,
    );
    assert!(compared > 0, "no complete reference set was found");
}

/// Measures the linear-fit divergence ADR 007 Phase 3 records as deliberate:
/// we refit the index statistics as the stack shrinks, Siril keeps the
/// originals. This compares two master flats built by the same commands apart
/// from the rejection method, so the difference isolates that choice.
#[test]
#[cfg_attr(debug_assertions, ignore = "reads 61 MP frames; run with --release")]
fn the_linear_fit_divergence_is_measured() {
    let Some((_, root)) = reference_roots().into_iter().next() else {
        eprintln!("skipping: run `cargo xtask siril-reference --calibration`");
        return;
    };
    let (Some(winsorized), Some(linear)) = (
        reference(&root, "masters/master_flat_winsorized.fits"),
        reference(&root, "masters/master_flat_linear.fits"),
    ) else {
        eprintln!("skipping: no master flats under {}", root.display());
        return;
    };

    let w = load(&winsorized);
    let l = load(&linear);
    let stats_w = ChannelStats::compute(w.channel(0), w.width(), w.height());
    let stats_l = ChannelStats::compute(l.channel(0), l.width(), l.height());
    let between_methods = compare(w.data(), l.data());

    println!(
        "siril's own two master flats differ by max {:.4} ADU, rms {:.5} ADU\n  \
         winsorized: median {:.2}, bgnoise {:.4}\n  \
         linear:     median {:.2}, bgnoise {:.4}\n  \
         This is the scale a rejection-method change moves a master flat, and \
         therefore the yardstick for the native linear-fit divergence.",
        between_methods.max_abs,
        between_methods.rms,
        stats_w.median as f64 * ADU,
        stats_w.background_noise * ADU,
        stats_l.median as f64 * ADU,
        stats_l.background_noise * ADU,
    );

    // Not an assertion about our code — it records the reference scale that a
    // native-vs-Siril linear-fit comparison has to be judged against, which
    // lands with the master-flat pipeline in Phase 5.
    assert!(between_methods.max_abs.is_finite());
}
